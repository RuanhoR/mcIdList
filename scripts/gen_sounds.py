def make_auto_translation(sound_id):
    """Generate automatic translations for a sound event based on its components."""
    parts = sound_id.split(".")
    en_parts, ja_parts, ko_parts, zh_parts = [], [], [], []
    for p in parts:
        if p in ACT:
            e, j, k, z = ACT[p]
            en_parts.append(e)
            ja_parts.append(j)
            ko_parts.append(k)
            zh_parts.append(z)
        elif p in BN:
            e, j, k, z = BN[p]
            en_parts.append(e)
            ja_parts.append(j)
            ko_parts.append(k)
            zh_parts.append(z)
        elif p in EN:
            e, j, k, z = EN[p]
            en_parts.append(e)
            ja_parts.append(j)
            ko_parts.append(k)
            zh_parts.append(z)
        else:
            title = p.replace("_", " ").title()
            en_parts.append(title)
            ja_parts.append(p)
            ko_parts.append(p)
            zh_parts.append(p)
    return t(" ".join(en_parts), "".join(ja_parts), " ".join(ko_parts), "".join(zh_parts))


def main():
    be_sounds = read_be_translations()
    je_ids = extract_je_sound_ids()

    result = {}

    for sound_id in je_ids:
        if sound_id in be_sounds:
            result[sound_id] = be_sounds[sound_id]
        elif sound_id in MANUAL_OVERRIDES:
            result[sound_id] = MANUAL_OVERRIDES[sound_id]
        else:
            result[sound_id] = make_auto_translation(sound_id)

    out_path = os.path.join(os.path.dirname(__file__), "je_sounds.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print(f"Generated {out_path} with {len(result)} sounds")


if __name__ == "__main__":
    main()
