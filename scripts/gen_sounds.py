def read_be_translations():
    be_path = os.path.join(os.path.dirname(__file__), "..", "data", "be_1.26.40.json")
    with open(be_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data.get("sound", {})


def extract_je_sound_ids():
    java_path = os.path.join(
        os.path.dirname(__file__), "..", "..", "..",
        "mcje", "decompiled_cfr", "net", "minecraft", "sounds", "SoundEvents.java"
    )
    with open(java_path, "r", encoding="utf-8") as f:
        content = f.read()
    ids = set()
    for m in re.finditer(r'\.register(?:ForHolder)?\("([^"]+)"\)', content):
        ids.add(m.group(1))
    return sorted(ids)


